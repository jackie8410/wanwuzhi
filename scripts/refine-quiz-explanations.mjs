const stageKeys = ['beginner', 'intermediate', 'advanced'];
export async function refineQuizExplanations(root, { check = false } = {}) {
if (!path.isAbsolute(root)) throw new Error('refineQuizExplanations requires an absolute project root');
const pendingWrites = [];
let updated = 0;
for (let domainId = 1; domainId <= 30; domainId += 1) {
  const file = path.join(root, 'data', 'curricula', `${domainId}.json`);
  const course = JSON.parse(await fs.readFile(file, 'utf8'));
  if (course.domainId !== domainId) throw new Error(`Domain mismatch in ${file}`);
  for (const [index, key] of stageKeys.entries()) {
    const stage = course.stages.find((item) => item.key === key);
    if (!stage || stage.quiz?.length !== 1) {
      throw new Error(`Expected exactly one quiz for ${domainId}/${key}; review mapping before writing`);
    }
    const quiz = stage.quiz[0];
    const [expectedAnswer, explanation] = explanations[domainId][index];
    const actualAnswer = quiz.options?.[quiz.correct];
    if (actualAnswer !== expectedAnswer) {
      throw new Error(`Answer changed for ${domainId}/${key}: expected ${JSON.stringify(expectedAnswer)}, got ${JSON.stringify(actualAnswer)}`);
    }
    quiz.explanation = explanation;
    updated += 1;
  }
  pendingWrites.push({ file, content: `${JSON.stringify(course, null, 2)}\n` });
}

if (!check) {
  for (const item of pendingWrites) await fs.writeFile(item.file, item.content);
}
return { mode: check ? 'validated-no-write' : 'updated', domains: pendingWrites.length, explanations: updated };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await refineQuizExplanations(process.cwd(), { check: process.argv.includes('--check') })));
}
